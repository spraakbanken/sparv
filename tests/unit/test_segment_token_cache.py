@pytest.fixture(scope="module")
def model_files(tmp_path_factory: pytest.TempPathFactory) -> tuple[Path, Path]:
    """Write the tokenizer config and token list to files."""  # noqa: DOC201
    directory = tmp_path_factory.mktemp("tokenizer")
    model = directory / "bettertokenizer.sv"
    model.write_text("\n".join(MODEL_LINES) + "\n", encoding="utf-8")
    token_list = directory / "bettertokenizer.sv.saldo-tokens"
    token_list.write_text("\n".join(TOKEN_LIST) + "\n", encoding="utf-8")
    return model, token_list


def _random_strings(n: int, seed: int = 0) -> list[str]:
    """Generate random strings of words, punctuation and whitespace."""  # noqa: DOC201
    rnd = random.Random(seed)
    strings = []
    for _ in range(n):
        s = "".join(rnd.choice(PIECES) + rnd.choice(SEPARATORS) for _ in range(rnd.randint(1, 8)))
        if rnd.random() < 0.3:  # noqa: PLR2004
            s = rnd.choice(SEPARATORS) + s
        strings.append(s)
    return strings


@pytest.mark.unit
@pytest.mark.noexternal
def test_token_cache_gives_same_result(model_files: tuple[Path, Path]) -> None:
    """Test that tokenizing with the cache gives the same tokens and spans as without it."""
    model, token_list = model_files
    plain = BetterWordTokenizer(model, token_list)
    cached = BetterWordTokenizer(model, token_list, cache=True)
    for s in EDGE_CASES + _random_strings(20_000):
        assert cached.word_tokenize(s) == plain.word_tokenize(s), repr(s)
        assert list(cached.span_tokenize(s)) == list(plain.span_tokenize(s)), repr(s)
    assert cached._cache


@pytest.mark.unit
@pytest.mark.noexternal
def test_token_cache_size_limit(model_files: tuple[Path, Path]) -> None:
    """Test that the cache is emptied when full, without affecting the result."""
    model, token_list = model_files
    plain = BetterWordTokenizer(model, token_list)
    cached = BetterWordTokenizer(model, token_list, cache=True)
    cached.cache_max_size = 10
    for s in _random_strings(2_000, seed=1):
        assert cached.word_tokenize(s) == plain.word_tokenize(s), repr(s)
        assert len(cached._cache) <= cached.cache_max_size
